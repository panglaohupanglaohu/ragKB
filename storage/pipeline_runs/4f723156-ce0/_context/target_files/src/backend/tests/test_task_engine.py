class TestAgentTask:
    """AgentTask 数据类单元测试."""

    def test_minimal_creation(self):
        task = AgentTask(
            task_id="task-001",
            title="测试任务",
            agent_id="agent-001",
        )
        assert task.task_id == "task-001"
        assert task.title == "测试任务"
        assert task.agent_id == "agent-001"
        assert task.status == TaskStatus.PENDING
        assert task.priority == 2  # NORMAL default
        assert task.dependencies == []
        assert task.result is None

    def test_priority_values(self):
        task = AgentTask(
            task_id="task-002",
            title="紧急任务",
            agent_id="agent-001",
            priority=1,  # HIGH
        )
        assert task.priority == 1

    def test_with_dependencies(self):
        task = AgentTask(
            task_id="task-003",
            title="有依赖的任务",
            agent_id="agent-001",
            dependencies=["task-001", "task-002"],
        )
        assert len(task.dependencies) == 2
        assert "task-001" in task.dependencies

    def test_status_transitions(self):
        task = AgentTask(task_id="task-004", title="t", agent_id="a1")
        assert task.status == TaskStatus.PENDING
        task.status = TaskStatus.RUNNING
        assert task.status == TaskStatus.RUNNING
        task.status = TaskStatus.COMPLETED
        assert task.status == TaskStatus.COMPLETED

    def test_created_at_set_on_init(self):
        task = AgentTask(task_id="task-005", title="t", agent_id="a1")
        assert task.created_at is not None
        assert task.created_at != ""
        assert task.completed_at == ""

    def test_to_dict(self):
        task = AgentTask(
            task_id="task-006",
            title="ToDict Test",
            agent_id="a1",
            priority=1,  # HIGH
            dependencies=["dep1"],
        )
        d = task.to_dict()
        assert d["task_id"] == "task-006"
        assert d["title"] == "ToDict Test"
        assert d["priority"] == 1
        assert d["dependencies"] == ["dep1"]

    def test_task_id_autogenerated(self):
        task = AgentTask(title="Auto ID", agent_id="a1")
        assert task.task_id != ""
        assert len(task.task_id) > 0


