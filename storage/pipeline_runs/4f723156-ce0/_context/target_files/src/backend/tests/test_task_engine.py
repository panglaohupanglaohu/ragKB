class TestTaskEnums:
    """任务枚举值测试."""

    def test_task_status_values(self):
        values = {s.value for s in TaskStatus}
        assert "pending" in values
        assert "running" in values
        assert "completed" in values
        assert "failed" in values
        assert "cancelled" in values
        # 确认没有 blocked 状态
        assert "blocked" not in values

    def test_task_priority_values(self):
        values = {p.value for p in TaskPriority}
        assert 0 in values  # CRITICAL
        assert 1 in values  # HIGH
        assert 2 in values  # NORMAL
        assert 3 in values  # LOW

    def test_priority_ordering(self):
        # Lower value = higher priority: critical(0) > high(1) > normal(2) > low(3)
        assert TaskPriority.CRITICAL.value < TaskPriority.HIGH.value
        assert TaskPriority.HIGH.value < TaskPriority.NORMAL.value
        assert TaskPriority.NORMAL.value < TaskPriority.LOW.value
