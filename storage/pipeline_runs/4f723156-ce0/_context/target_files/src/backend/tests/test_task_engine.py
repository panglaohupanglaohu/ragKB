class TestTaskEngine:
    """TaskEngine 任务调度引擎单元测试."""

    def test_initialization(self, task_engine):
        assert task_engine._max_concurrency == 4
        stats = task_engine.stats()
        assert stats["total"] >= 0  # may have stale tasks from disk

    def test_submit_task(self, task_engine):
        async def _test():
            task = await task_engine.submit_task(
                AgentTask(title="Test Submit", agent_id="agent-001")
            )
            assert task is not None
            assert task.task_id is not None
            assert task.title == "Test Submit"
            assert task.status == TaskStatus.PENDING
        asyncio.run(_test())

    def test_submit_with_priority(self, task_engine):
        async def _test():
            task = await task_engine.submit_task(
                AgentTask(title="High Priority", agent_id="agent-001", priority=1)
            )
            assert task.priority == 1
        asyncio.run(_test())

    def test_submit_with_dependencies(self, task_engine):
        async def _test():
            dep_task = await task_engine.submit_task(
                AgentTask(title="Dep", agent_id="a1")
            )
            task = await task_engine.submit_task(
                AgentTask(
                    title="Dependent Task",
                    agent_id="a1",
                    dependencies=[dep_task.task_id],
                )
            )
            assert dep_task.task_id in task.dependencies
        asyncio.run(_test())

    def test_get_task_by_id(self, task_engine):
        async def _test():
            task = await task_engine.submit_task(
                AgentTask(title="Find Me", agent_id="a1")
            )
            found = task_engine.get_task(task.task_id)
            assert found is not None
            assert found.task_id == task.task_id
        asyncio.run(_test())

    def test_get_nonexistent_task(self, task_engine):
        result = task_engine.get_task("nonexistent-id")
        assert result is None

    def test_get_agent_tasks(self, task_engine):
        async def _test():
            await task_engine.submit_task(
                AgentTask(title="A1 Task", agent_id="a1")
            )
            await task_engine.submit_task(
                AgentTask(title="A2 Task", agent_id="a2")
            )
            await task_engine.submit_task(
                AgentTask(title="A1 Task 2", agent_id="a1")
            )
            a1_tasks = task_engine.get_agent_tasks("a1")
            assert len(a1_tasks) == 2
            a2_tasks = task_engine.get_agent_tasks("a2")
            assert len(a2_tasks) == 1
        asyncio.run(_test())

    def test_complete_task(self, task_engine):
        async def _test():
            task = await task_engine.submit_task(
                AgentTask(title="Complete Me", agent_id="a1")
            )
            result = await task_engine.complete_task(task.task_id)
            assert result is not None
            assert result.status == TaskStatus.COMPLETED
            assert result.completed_at is not None
            assert result.completed_at != ""
        asyncio.run(_test())

    def test_complete_nonexistent_task(self, task_engine):
        async def _test():
            result = await task_engine.complete_task("no-such-id")
            assert result is None
        asyncio.run(_test())

    def test_stats(self, task_engine):
        async def _test():
            await task_engine.submit_task(
                AgentTask(title="Task 1", agent_id="a1")
            )
            await task_engine.submit_task(
                AgentTask(title="Task 2", agent_id="a2")
            )
            stats = task_engine.stats()
            assert stats["total"] == 2
        asyncio.run(_test())

    def test_stats_after_completion(self, task_engine):
        async def _test():
            task = await task_engine.submit_task(
                AgentTask(title="Todo", agent_id="a1")
            )
            await task_engine.complete_task(task.task_id)
            stats = task_engine.stats()
            assert stats["total"] == 1
            assert stats["by_status"]["completed"] == 1
        asyncio.run(_test())

    def test_max_concurrency(self, task_engine):
        engine = TaskEngine(max_concurrency=2)
        assert engine.max_concurrency == 2

    def test_submit_description(self, task_engine):
        async def _test():
            task = await task_engine.submit_task(
                AgentTask(
                    title="With Desc",
                    agent_id="a1",
                    description="这是一段描述",
                )
            )
            assert task.description == "这是一段描述"
        asyncio.run(_test())

    def test_cancel_task(self, task_engine):
        async def _test():
            task = await task_engine.submit_task(
                AgentTask(title="Cancel Me", agent_id="a1")
            )
            result = await task_engine.cancel_task(task.task_id)
            assert result is not None
            assert result.status == TaskStatus.CANCELLED
        asyncio.run(_test())

    def test_fail_task(self, task_engine):
        async def _test():
            task = await task_engine.submit_task(
                AgentTask(title="Fail Me", agent_id="a1")
            )
            result = await task_engine.fail_task(task.task_id, "测试失败")
            assert result is not None
            assert result.status == TaskStatus.FAILED
            assert result.error == "测试失败"
        asyncio.run(_test())

    def test_delete_task(self, task_engine):
        async def _test():
            task = await task_engine.submit_task(
                AgentTask(title="Delete Me", agent_id="a1")
            )
            deleted = await task_engine.delete_task(task.task_id)
            assert deleted is not None
            assert task_engine.get_task(task.task_id) is None
        asyncio.run(_test())

    def test_team_tasks(self, task_engine):
        async def _test():
            await task_engine.submit_task(
                AgentTask(title="Team A Task", agent_id="a1", team_id="team-1")
            )
            await task_engine.submit_task(
                AgentTask(title="Team B Task", agent_id="a1", team_id="team-2")
            )
            team_tasks = task_engine.get_team_tasks("team-1")
            assert len(team_tasks) == 1
            assert team_tasks[0].team_id == "team-1"
        asyncio.run(_test())


