export function getPlazaLanguage() {
  return globalThis.window?.PX_I18N?.getLang?.() === 'en' ? 'en' : 'zh';
}

export function plazaT(key, params = {}, lang = getPlazaLanguage()) {
  const template = MESSAGES[lang]?.[key] ?? MESSAGES.zh[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`));
}

export function applyPlazaTranslations(root = document) {
  root.querySelectorAll('[data-plaza-i18n]').forEach((element) => {
    element.textContent = plazaT(element.dataset.plazaI18n);
  });
  ['title', 'placeholder', 'aria-label'].forEach((attribute) => {
    const dataName = `plazaI18n${attribute.replace(/(^|-)([a-z])/g, (_, __, letter) => letter.toUpperCase())}`;
    root.querySelectorAll(`[data-plaza-i18n-${attribute}]`).forEach((element) => {
      element.setAttribute(attribute, plazaT(element.dataset[dataName]));
    });
  });
  if (globalThis.document && root === globalThis.document) globalThis.document.title = plazaT('page.title');
}

